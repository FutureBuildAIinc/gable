use tauri_build::{AppManifest, Attributes};

// Every command the webview may call is declared here, so Tauri applies an
// ACL to it and the capability must allow it by name. An undeclared app
// command would be open to every window. Pro declares the two token
// commands and the two sign in commands and nothing else (the webview never reaches the custody slot
// itself): no keychain command, no filesystem, no shell.
//
// tauri-build writes permissions/autogenerated/*.toml for these names and
// never deletes a stale one, and it reads every file there, so
// `drop_stale_permissions` removes any file whose command is not in this
// list before tauri-build reads the folder. The folder is generated and
// git ignored: it appears on every build and is never committed.
const COMMANDS: &[&str] = &[
    "core_token",
    "clear_tokens",
    "begin_sign_in",
    "refresh_tokens",
];

fn drop_stale_permissions() {
    let Ok(entries) = std::fs::read_dir("permissions/autogenerated") else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let stem = path.file_stem().and_then(|s| s.to_str()).unwrap_or("");
        if path.extension().is_some_and(|e| e == "toml") && !COMMANDS.contains(&stem) {
            let _ = std::fs::remove_file(&path);
        }
    }
}

fn main() {
    drop_stale_permissions();
    println!("cargo:rerun-if-changed=capabilities");
    tauri_build::try_build(
        Attributes::new()
            .app_manifest(AppManifest::new().commands(COMMANDS))
            .capabilities_path_pattern("./capabilities/*.json"),
    )
    .expect("failed to run tauri-build");
}
